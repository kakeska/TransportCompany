CREATE TABLE carriers (
    carrier_id NUMBER GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,
    carrier_name VARCHAR2(100) NOT NULL,
    country VARCHAR(50),
    rating NUMBER(2,1)
);

CREATE TABLE cities (
    city_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_name VARCHAR(100) NOT NULL,
    country VARCHAR(50)NOT NULL,
    CONSTRAINT unikalna_para UNIQUE (city_name, country)
);

CREATE TABLE delivery_status(
    status_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status_name VARCHAR(15) NOT NULL,
    CONSTRAINT unikalny_status UNIQUE (status_name)
);

CREATE TABLE deliveries (
    delivery_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carriers_id INT NOT NULL,
    route_from INT NOT NULL,
    route_to INT NOT NULL,
    delivery_planned_date DATE NOT NULL,
    delivery_date DATE,
    status_id INT NOT NULL,
    delivery_cost NUMBER(18,2),
    FOREIGN KEY (carriers_id) REFERENCES carriers(carrier_id),
    FOREIGN KEY (route_from) REFERENCES cities(city_id),
    FOREIGN KEY (route_to) REFERENCES cities(city_id),
    FOREIGN KEY (status_id) REFERENCES delivery_status(status_id),
    CONSTRAINT chk_unikalnosc_punktow CHECK (route_from <> route_to),
    CONSTRAINT chk_dodatiosc_kosztu CHECK (delivery_cost >= 0)
)